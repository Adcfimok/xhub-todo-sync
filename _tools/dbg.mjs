import { chromium } from 'playwright'
const b = await chromium.launch({ channel: 'msedge' })
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true })
const p = await ctx.newPage()
p.on('pageerror', (e) => console.log('[pageerror]', e.message))
p.on('console', (m) => console.log('[console]', m.type(), m.text()))
await p.goto('http://127.0.0.1:8100/index.html', { waitUntil: 'networkidle' })
await p.waitForTimeout(800)
console.log('tab style:', await p.evaluate(() => document.getElementById('tabbar').style.cssText))
console.log('tab-i attr:', await p.evaluate(() => document.getElementById('tabbar').getAttribute('style')))
await p.evaluate(() => (location.hash = '#/ai'))
await p.waitForTimeout(800)
console.log('ai dom:', await p.evaluate(() => document.getElementById('page').innerHTML.slice(0, 300)))
console.log('title:', await p.evaluate(() => document.getElementById('page-title').textContent))
console.log('tab-i now:', await p.evaluate(() => document.getElementById('tabbar').style.cssText))
await b.close()
